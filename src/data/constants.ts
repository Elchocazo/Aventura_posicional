export function getStageByLevel(level: GradeLevel): ProgressiveStage {
  return PROGRESSIVE_STAGES.find((s) => s.level === level) || PROGRESSIVE_STAGES[0];
}

export function getNextStage(level: GradeLevel): ProgressiveStage | null {
  const idx = PROGRESSIVE_STAGES.findIndex((s) => s.level === level);
  if (idx < 0 || idx >= PROGRESSIVE_STAGES.length - 1) return null;
  return PROGRESSIVE_STAGES[idx + 1];
}

